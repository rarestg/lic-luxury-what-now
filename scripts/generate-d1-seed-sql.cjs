#!/usr/bin/env node
/*
Generate apps/worker/seed/seed.sql from local graph artifacts.
*/

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const LISTINGS_PATH = path.join(ROOT, "data", "listings.json");
const GRAPH_PATH = path.join(ROOT, "data", "hash-graph", "listing-graph.json");
const OUT_PATH = path.join(ROOT, "apps", "worker", "seed", "seed.sql");
const hasDestructiveReset = process.argv.includes("--destructive-reset");
const hasPruneUnreferencedListings = process.argv.includes("--prune-unreferenced-listings");

function q(value) {
  if (value == null) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function i(value) {
  const n = Number(value);
  return Number.isFinite(n) ? String(Math.trunc(n)) : "NULL";
}

function f(value) {
  const n = Number(value);
  return Number.isFinite(n) ? String(n) : "NULL";
}

function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function main() {
  if (!fs.existsSync(LISTINGS_PATH) || !fs.existsSync(GRAPH_PATH)) {
    throw new Error("Missing data/listings.json or data/hash-graph/listing-graph.json");
  }

  const listings = JSON.parse(fs.readFileSync(LISTINGS_PATH, "utf8"));
  const graph = JSON.parse(fs.readFileSync(GRAPH_PATH, "utf8"));
  const generatedAt = String(graph.generatedAt || new Date().toISOString());
  const runId = "active";

  const componentByListing = new Map();
  const components = Array.isArray(graph.components) ? graph.components : [];
  for (const component of components) {
    const cid = Number(component?.componentId);
    const ids = Array.isArray(component?.listingIds) ? component.listingIds : [];
    if (!Number.isFinite(cid)) continue;
    for (const id of ids) componentByListing.set(String(id), cid);
  }

  const lines = [];
  // Intentionally no explicit BEGIN/COMMIT statements in generated SQL.
  // Cloudflare D1 imports via `wrangler d1 execute --file` reject transaction
  // statements, so this file must stay transaction-free for remote execution.
  lines.push("-- Auto-generated by scripts/generate-d1-seed-sql.js");
  lines.push("-- Note: D1 remote imports via wrangler reject explicit BEGIN/COMMIT statements.");
  lines.push("-- Keep this file transaction-free for `wrangler d1 execute --file` compatibility.");
  lines.push("PRAGMA foreign_keys = OFF;");
  if (hasDestructiveReset) {
    lines.push("DELETE FROM listing_address_assignments;");
    lines.push("DELETE FROM address_assertions;");
    lines.push("DELETE FROM listing_edges;");
    lines.push("DELETE FROM listings;");
    lines.push("DELETE FROM runs WHERE id = 'active';");
    lines.push(
      `INSERT INTO runs (id, created_at, phash_threshold, dhash_threshold, notes) VALUES (${q(runId)}, ${q(generatedAt)}, ${i(graph?.thresholds?.phashDistanceMax)}, ${i(graph?.thresholds?.dhashDistanceMax)}, ${q("Imported from local listing-graph.json")});`,
    );
  } else {
    lines.push(
      `INSERT INTO runs (id, created_at, phash_threshold, dhash_threshold, notes)
       VALUES (${q(runId)}, ${q(generatedAt)}, ${i(graph?.thresholds?.phashDistanceMax)}, ${i(graph?.thresholds?.dhashDistanceMax)}, ${q("Imported from local listing-graph.json")})
       ON CONFLICT(id) DO UPDATE SET
         created_at = excluded.created_at,
         phash_threshold = excluded.phash_threshold,
         dhash_threshold = excluded.dhash_threshold,
         notes = excluded.notes;`,
    );
  }

  for (const listing of listings) {
    const id = String(listing && listing.id != null ? listing.id : "").trim();
    if (!id) continue;
    const listingMetadataJson = JSON.stringify(listing || {});
    if (hasDestructiveReset) {
      lines.push(
        `INSERT INTO listings (id, web_id, title, source_url, price, beds, baths, sqft, updated_at, component_id, metadata_json) VALUES (${q(id)}, ${q(id)}, ${q(listing.title || "")}, ${q(listing.url || "")}, ${i(listing.price)}, ${i(listing.beds)}, ${i(listing.baths)}, ${i(listing.sqft)}, ${q(generatedAt)}, ${i(componentByListing.get(id))}, ${q(listingMetadataJson)});`,
      );
    } else {
      lines.push(
        `INSERT INTO listings (id, web_id, title, source_url, price, beds, baths, sqft, updated_at, component_id, metadata_json)
         VALUES (${q(id)}, ${q(id)}, ${q(listing.title || "")}, ${q(listing.url || "")}, ${i(listing.price)}, ${i(listing.beds)}, ${i(listing.baths)}, ${i(listing.sqft)}, ${q(generatedAt)}, ${i(componentByListing.get(id))}, ${q(listingMetadataJson)})
         ON CONFLICT(id) DO UPDATE SET
           web_id = excluded.web_id,
           title = excluded.title,
           source_url = excluded.source_url,
           price = excluded.price,
           beds = excluded.beds,
           baths = excluded.baths,
           sqft = excluded.sqft,
           updated_at = excluded.updated_at,
           component_id = excluded.component_id,
           metadata_json = excluded.metadata_json;`,
      );
    }
  }

  if (!hasDestructiveReset && hasPruneUnreferencedListings) {
    const listingIds = listings
      .map((listing) => String(listing && listing.id != null ? listing.id : "").trim())
      .filter(Boolean);
    if (listingIds.length) {
      lines.push(
        `DELETE FROM listings
         WHERE id NOT IN (${listingIds.map((id) => q(id)).join(", ")})
           AND id NOT IN (SELECT DISTINCT listing_id FROM address_assertions)
           AND id NOT IN (SELECT DISTINCT listing_id FROM listing_address_assignments);`,
      );
    }
  }

  if (!hasDestructiveReset) {
    lines.push(`DELETE FROM listing_edges WHERE run_id = ${q(runId)};`);
  }

  const edges = Array.isArray(graph.edges) ? graph.edges : [];
  for (const edge of edges) {
    const a = String(edge && edge.source != null ? edge.source : "").trim();
    const b = String(edge && edge.target != null ? edge.target : "").trim();
    if (!a || !b) continue;
    const sampleImagePairs = Array.isArray(edge?.sampleImagePairs) ? edge.sampleImagePairs : [];
    const sampleImagePairsJson = JSON.stringify(sampleImagePairs);
    lines.push(
      `INSERT INTO listing_edges (run_id, listing_a_id, listing_b_id, matched_image_pairs, min_phash_distance, min_dhash_distance, avg_phash_distance, avg_dhash_distance, sample_image_pairs_json) VALUES (${q(runId)}, ${q(a)}, ${q(b)}, ${i(edge.matchedImagePairs)}, ${i(edge.minPhashDistance)}, ${i(edge.minDhashDistance)}, ${f(edge.avgPhashDistance)}, ${f(edge.avgDhashDistance)}, ${q(sampleImagePairsJson)});`,
    );
  }

  lines.push("PRAGMA foreign_keys = ON;");
  ensureDir(OUT_PATH);
  fs.writeFileSync(OUT_PATH, `${lines.join("\n")}\n`, "utf8");
  console.log(`Wrote ${OUT_PATH}`);
  if (hasDestructiveReset) {
    console.log("Mode: DESTRUCTIVE RESET (assertions and assignments are wiped).");
  } else {
    console.log("Mode: SAFE (preserving assertions and assignments).");
    if (hasPruneUnreferencedListings) {
      console.log("Prune: enabled for unreferenced listings without assertions/assignments.");
    }
  }
  console.log(
    `Rows: listings=${listings.length}, edges=${edges.length}, components=${components.length}`,
  );
}

main();
