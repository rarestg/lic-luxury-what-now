#!/usr/bin/env node
/*
Generate tool/config.local.js from .env so browser code can read runtime config
without hardcoding secrets in source files.
*/

const fs = require("node:fs");
const path = require("node:path");

const ROOT_DIR = path.resolve(__dirname, "..");
const ENV_PATH = path.join(ROOT_DIR, ".env");
const OUT_PATH = path.join(ROOT_DIR, "tool", "config.local.js");

function parseEnv(contents) {
  const env = Object.create(null);
  const lines = contents.split(/\r?\n/);
  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const idx = line.indexOf("=");
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

function resolve(fileEnv, key) {
  // Environment variables take precedence over .env file values
  return String(process.env[key] || fileEnv[key] || "").trim();
}

function isTruthy(value) {
  return ["1", "true", "yes", "on"].includes(
    String(value || "")
      .trim()
      .toLowerCase(),
  );
}

function main() {
  let fileEnv = Object.create(null);
  if (fs.existsSync(ENV_PATH)) {
    fileEnv = parseEnv(fs.readFileSync(ENV_PATH, "utf8"));
  } else {
    console.log(`No .env file found at ${ENV_PATH}, using environment variables only.`);
  }

  const geocodeEndpoint = resolve(fileEnv, "LIC_GEOCODE_ENDPOINT");
  const googleMapsApiKey = resolve(fileEnv, "LIC_GOOGLE_MAPS_API_KEY");
  const apiBaseUrl = resolve(fileEnv, "LIC_API_BASE_URL");
  const forbidBrowserGoogleMapsKey = isTruthy(
    resolve(fileEnv, "LIC_FORBID_BROWSER_GOOGLE_MAPS_KEY"),
  );
  const useApiAssertions = ["1", "true", "yes", "on"].includes(
    resolve(fileEnv, "LIC_USE_API_ASSERTIONS").toLowerCase(),
  );

  // Safety guard: production Worker bundles should never expose a browser Google Maps key.
  // Use the server-side `/api/geocode` path with Worker secret `GOOGLE_MAPS_API_KEY` instead.
  if (forbidBrowserGoogleMapsKey && googleMapsApiKey) {
    throw new Error(
      "LIC_GOOGLE_MAPS_API_KEY must be empty when LIC_FORBID_BROWSER_GOOGLE_MAPS_KEY=1. Use LIC_GEOCODE_ENDPOINT and Worker secret GOOGLE_MAPS_API_KEY instead.",
    );
  }

  const payload = {
    geocodeEndpoint,
    googleMapsApiKey,
    apiBaseUrl,
    useApiAssertions,
  };

  const output = `/* Auto-generated by scripts/generate-tool-config.js. */
window.LIC_CONFIG = Object.assign({}, window.LIC_CONFIG || {}, ${JSON.stringify(payload, null, 2)});
`;

  fs.writeFileSync(OUT_PATH, output, "utf8");
  console.log(`Wrote ${OUT_PATH}`);
  if (!geocodeEndpoint && !googleMapsApiKey) {
    console.log("Note: both geocoding settings are empty; Geocode button will be disabled.");
  } else if (geocodeEndpoint) {
    console.log(`Using backend geocode endpoint: ${geocodeEndpoint}`);
  } else {
    console.log("Using direct browser geocoding with LIC_GOOGLE_MAPS_API_KEY.");
  }
  if (forbidBrowserGoogleMapsKey) {
    console.log("Browser Google Maps key guard is enabled (LIC_FORBID_BROWSER_GOOGLE_MAPS_KEY=1).");
  }
  if (useApiAssertions) {
    console.log(
      `API assertions enabled${apiBaseUrl ? ` (base: ${apiBaseUrl})` : " (same-origin /api)"} .`,
    );
  } else {
    console.log("API assertions disabled; UI stays local-only for saves.");
  }
}

main();
